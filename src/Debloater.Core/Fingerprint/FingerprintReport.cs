using System.Globalization;
using System.Text;
using Debloater.Core.Inventory;

namespace Debloater.Core.Fingerprint;

/// <summary>Markdown report of a <see cref="FingerprintDiffResult"/>, in order of usefulness.</summary>
public static class FingerprintReport
{
    public const string HumanReadingHeading = "## Human reading";

    private const int MaxRowsPerList = 150;

    public static string ToMarkdown(FingerprintDiffResult d, int top = 100)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# Build diff: {d.Old.Build} → {d.New.Build}");
        sb.AppendLine();
        sb.AppendLine(string.Create(Inv, $"Generated by `Debloater.Cli fingerprint diff` on {d.CreatedUtc:yyyy-MM-dd HH:mm} UTC. Only names, paths and versions; ") +
                      "no binary content beyond the strings that match the patterns. See \"How to read\" at the end.");
        sb.AppendLine();
        sb.AppendLine(HumanReadingHeading);
        sb.AppendLine();
        sb.AppendLine("_(To be filled in by the maintainer: the most interesting findings, with the confidence level of each.)_");
        sb.AppendLine();

        // ---- summary ----
        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine("| | Old | New |");
        sb.AppendLine("|---|---|---|");
        Row(sb, "Build", d.Old.Build, d.New.Build);
        Row(sb, "Edition / version", $"{d.Old.Edition} {d.Old.DisplayVersion}", $"{d.New.Edition} {d.New.DisplayVersion}");
        Row(sb, "Source", Origin(d.Old), Origin(d.New));
        Row(sb, "Binary scan", string.Create(Inv, $"{d.Old.BinaryMode}: {d.Old.Binaries:N0} PE, {d.Old.Strings:N0} strings"), string.Create(Inv, $"{d.New.BinaryMode}: {d.New.Binaries:N0} PE, {d.New.Strings:N0} strings"));
        Row(sb, "ADMX policies", d.Old.Policies.ToString("N0", Inv), d.New.Policies.ToString("N0", Inv));
        Row(sb, "Inventory items", d.Old.InventoryItems.ToString("N0", Inv), d.New.InventoryItems.ToString("N0", Inv));
        sb.AppendLine();
        sb.AppendLine("| Category | Count |");
        sb.AppendLine("|---|---:|");
        foreach (var c in d.Counts) sb.AppendLine($"| {Esc(c.Label)} | {c.Value.ToString("N0", Inv)} |");
        sb.AppendLine();
        if (d.Warnings.Count > 0)
        {
            sb.AppendLine("Warnings:");
            sb.AppendLine();
            foreach (var w in d.Warnings) sb.AppendLine($"- {w}");
            sb.AppendLine();
        }
        var privacy = d.Privacy;
        if (privacy is not null)
        {
            sb.AppendLine($"**Privacy:** filter on (`--no-privacy` turns it off). {privacy.Total.ToString("N0", Inv)} item(s) omitted: " +
                          "third-party/hardware/separately installed items (on both sides), whatever only existed on the source PC with no evidence of being part of Windows " +
                          "(binaries, services, drivers, tasks, apps, capabilities, strings and references to old binaries) and the machine names. " +
                          "The counts above are from before the filter.");
            sb.AppendLine();
        }

        // ---- candidates ----
        var open = d.Candidates.Where(c => c.CoveredBy.Count == 0).Take(top).ToList();
        sb.AppendLine($"## Top {open.Count} candidates (not covered by the catalog)");
        sb.AppendLine();
        sb.AppendLine("Score = investigation order, not proof. `new` = did not exist in the old build; `moved` = existed in another binary.");
        sb.AppendLine("The full list (with the binaries' SHA-256) is in the JSON (`candidates`).");
        sb.AppendLine();
        CandidateTable(sb, open);

        // ---- ADMX ----
        var addedPolicies = d.Policies.Where(p => p.Change == DiffChange.Added).ToList();
        sb.AppendLine($"## New ADMX policies ({addedPolicies.Count})");
        sb.AppendLine();
        if (addedPolicies.Count == 0) sb.AppendLine("None.");
        else
        {
            sb.AppendLine("| Policy | Class | Key \\ value | Supported on | Display name |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var p in addedPolicies.Take(MaxRowsPerList))
                sb.AppendLine($"| {Code(p.Policy.QualifiedName)}{(p.Note is null ? "" : $" ({p.Note})")} | {p.Policy.Class} | {Code(string.Join("; ", p.Policy.Values.Take(4)))}{(p.Policy.Values.Count > 4 ? $" (+{p.Policy.Values.Count - 4})" : "")} | {Esc(p.Policy.SupportedOn)} | {Esc(p.Policy.DisplayName)} |");
            More(sb, addedPolicies.Count);
        }
        sb.AppendLine();

        var changedPolicies = d.Policies.Where(p => p.Change == DiffChange.Changed).ToList();
        sb.AppendLine($"## Changed ADMX policies ({changedPolicies.Count})");
        sb.AppendLine();
        if (changedPolicies.Count == 0) sb.AppendLine("None.");
        foreach (var p in changedPolicies.Take(MaxRowsPerList))
            sb.AppendLine($"- {Code(p.Policy.QualifiedName)}: {Esc(string.Join("; ", p.Details))}");
        More(sb, changedPolicies.Count);
        sb.AppendLine();

        var removedPolicies = d.Policies.Where(p => p.Change == DiffChange.Removed).ToList();
        sb.AppendLine($"## Removed ADMX policies ({removedPolicies.Count})");
        sb.AppendLine();
        if (removedPolicies.Count == 0) sb.AppendLine("None.");
        Omitted(sb, privacy, FingerprintPrivacyInfo.Policies, "policy(ies) from ADMX templates that only existed on the source PC");
        foreach (var g in removedPolicies.GroupBy(p => p.Note).OrderBy(g => g.Key is null ? 0 : 1))
        {
            if (g.Key is not null) sb.AppendLine($"- _{g.Key}_: {string.Join(", ", g.Select(p => p.Policy.File).Distinct(StringComparer.OrdinalIgnoreCase).Select(Code))} ({g.Count()} policies)");
            else foreach (var p in g.Take(MaxRowsPerList)) sb.AppendLine($"- {Code(p.Policy.QualifiedName)} ({Code(string.Join("; ", p.Policy.Values.Take(3)))})");
        }
        sb.AppendLine();

        // ---- catalog ----
        sb.AppendLine($"## Possibly obsolete catalog tweaks ({d.PossiblyObsolete.Count})");
        sb.AppendLine();
        sb.AppendLine("The value name (or the key) was in some binary of the old build and is in none of the new one, or it left the ADMX. " +
                      "This does not prove the tweak stopped working (the value may be read by a binary outside the scan, or built at run time): check in the VM.");
        sb.AppendLine();
        if (d.PossiblyObsolete.Count == 0) sb.AppendLine("None.");
        foreach (var t in d.PossiblyObsolete)
            sb.AppendLine($"- {Code(t.TweakId)}: {Code(string.Join("; ", t.Targets))}. {Esc(string.Join("; ", t.Reasons))}. Previously in: {Esc(string.Join(", ", t.OldBinaries.Take(3)))}");
        sb.AppendLine();

        // ---- inventory ----
        sb.AppendLine("## Inventory");
        sb.AppendLine();
        sb.AppendLine("Changes flagged as \"environment\" come from hardware, separately installed apps or the user (noise when the machines differ).");
        sb.AppendLine();
        foreach (var kind in InventoryKinds.All)
        {
            var items = d.Inventory.Where(i => i.Kind == kind).ToList();
            var omitted = privacy?.Get(FingerprintPrivacyInfo.Inventory(kind)) ?? 0;
            if (items.Count == 0 && omitted == 0) continue;
            sb.AppendLine($"### {KindTitle(kind)}");
            sb.AppendLine();
            foreach (var change in new[] { DiffChange.Added, DiffChange.Removed, DiffChange.Changed })
            {
                var sys = items.Where(i => i.Change == change && i.Noise is null).ToList();
                if (sys.Count == 0) continue;
                sb.AppendLine($"**{ChangeTitle(change)} ({sys.Count})**");
                sb.AppendLine();
                foreach (var i in sys.Take(MaxRowsPerList))
                {
                    var name = i.DisplayName is { Length: > 0 } dn && !dn.Equals(i.Id, StringComparison.OrdinalIgnoreCase) ? $" — {Esc(dn)}" : "";
                    var tweaks = i.TweakIds.Count > 0 ? $" (tweaks: {string.Join(", ", i.TweakIds.Select(Code))})" : "";
                    var details = change == DiffChange.Changed || kind is InventoryKinds.Services ? $": {Esc(Short(string.Join("; ", i.Details), 160))}" : "";
                    sb.AppendLine($"- {Code(i.Id)}{name}{tweaks}{details}");
                }
                More(sb, sys.Count);
                sb.AppendLine();
            }
            var noise = items.Where(i => i.Noise is not null).ToList();
            if (noise.Count > 0)
            {
                sb.AppendLine($"<details><summary>{noise.Count} likely from the environment</summary>");
                sb.AppendLine();
                foreach (var g in noise.GroupBy(i => i.Noise))
                    sb.AppendLine($"- {Esc(g.Key)}: {string.Join(", ", g.Take(40).Select(i => $"{Sign(i.Change)}{Code(i.Id)}"))}{(g.Count() > 40 ? $" (+{g.Count() - 40})" : "")}");
                sb.AppendLine();
                sb.AppendLine("</details>");
                sb.AppendLine();
            }
            if (omitted > 0)
            {
                sb.AppendLine($"_{omitted.ToString("N0", Inv)} third-party/hardware item(s) or item(s) that only existed on the source PC were omitted (privacy)._");
                sb.AppendLine();
            }
        }

        // ---- binaries ----
        sb.AppendLine("## Binaries");
        sb.AppendLine();
        foreach (var change in new[] { DiffChange.Added, DiffChange.Removed })
        {
            var list = d.Binaries.Where(b => b.Change == change).ToList();
            sb.AppendLine($"**{ChangeTitle(change)} ({list.Count}; {list.Count(b => b.Curated)} from the curated list)**");
            sb.AppendLine();
            foreach (var b in list.Take(MaxRowsPerList))
                sb.AppendLine($"- {Code(b.Path)} {b.NewVersion ?? b.OldVersion}{(b.Curated ? " ★" : "")}");
            More(sb, list.Count);
            if (change == DiffChange.Removed) Omitted(sb, privacy, FingerprintPrivacyInfo.Binaries, "binary(ies) that only existed on the source PC (outside `Windows\\SystemApps`)");
            sb.AppendLine();
        }
        var versions = d.Binaries.Where(b => b.Change == DiffChange.Changed).ToList();
        sb.AppendLine($"**Version changed: {versions.Count}** ({versions.Count(b => b.Curated)} from the curated list). Most common versions in the new one: " +
                      string.Join(", ", versions.GroupBy(b => b.NewVersion).OrderByDescending(g => g.Count()).Take(5).Select(g => $"{g.Key} ({g.Count()})")) + ".");
        sb.AppendLine();

        // ---- already covered and disappeared ----
        var covered = d.Candidates.Where(c => c.CoveredBy.Count > 0).ToList();
        sb.AppendLine($"## Candidates already covered by the catalog ({covered.Count})");
        sb.AppendLine();
        foreach (var c in covered.Take(MaxRowsPerList))
            sb.AppendLine($"- {Code(c.Value)} ({c.Kind}, {c.Status}) → {string.Join(", ", c.CoveredBy.Select(Code))}");
        if (covered.Count == 0) sb.AppendLine("None.");
        More(sb, covered.Count);
        sb.AppendLine();

        var removed = d.RemovedStrings.Where(c => c.Score >= 40).Take(60).ToList();
        sb.AppendLine($"## Relevant strings that disappeared (top {removed.Count})");
        sb.AppendLine();
        sb.AppendLine("Present in some binary of the old build and in none of the new one. With different machines, many come from third-party/hardware binaries that only exist in the old one.");
        sb.AppendLine();
        if (removed.Count == 0) sb.AppendLine("None.");
        else
        {
            sb.AppendLine("| String | Kind | Score | Was in |");
            sb.AppendLine("|---|---|---:|---|");
            foreach (var c in removed)
                sb.AppendLine($"| {Code(Short(c.Value, 120))} | {c.Kind} | {c.Score} | {Esc(BinaryText(c))} |");
        }
        if (privacy?.Get(FingerprintPrivacyInfo.RemovedStrings) is > 0)
        {
            sb.AppendLine();
            Omitted(sb, privacy, FingerprintPrivacyInfo.RemovedStrings, "string(s) from binaries that do not exist in the new build");
        }
        sb.AppendLine();

        // ---- how to read ----
        sb.AppendLine("## How to read");
        sb.AppendLine();
        sb.AppendLine("- **Strings**: registry paths (`Software\\...`, `SYSTEM\\...`, `...\\Policies\\...`), value names with debloat patterns " +
                      "(`Disable*`, `Allow*`, `Enable*`, `Show*`, `Hide*`, `Taskbar*`, `*Enabled`, `SubscribedContent-*Enabled`, names with Copilot/Recall/Widget...), " +
                      "CSP paths (`./Device/Vendor/MSFT/...`), WNF and feature names, plus identifiers near (in the file) a registry path (`nearName`).");
        sb.AppendLine("- **Score**: base per kind (new ADMX policy 55, policy path 45, SubscribedContent 45, CSP 40, service 35, value name 25...), " +
                      "+ relevant key (Explorer\\Advanced, ContentDeliveryManager, WindowsCopilot...), + keywords (AI, Copilot, Recall, Widget, Ads, Suggest, " +
                      "Recommend, Telemetry, Diag...), + same key/binary as a catalog tweak, + curated/new binary; − log/trace/debug/test, COM/device keys, " +
                      "short names; `moved` is worth 30%; already covered by the catalog −40.");
        sb.AppendLine("- **Binary + version**: where the string appears in the new build (path relative to the root). This is the layer 2 input (reverse engineering).");
        return sb.ToString();
    }

    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    private static void CandidateTable(StringBuilder sb, List<Candidate> list)
    {
        if (list.Count == 0) { sb.AppendLine("None."); sb.AppendLine(); return; }
        sb.AppendLine("| # | String | Kind | Score | Binary (version) | Reason |");
        sb.AppendLine("|---:|---|---|---:|---|---|");
        foreach (var c in list)
        {
            var value = Code(Short(c.Value, 110));
            if (c.RegistryPath is not null && !c.RegistryPath.Equals(c.Value, StringComparison.OrdinalIgnoreCase))
                value += $"<br>in {Code(Short(c.RegistryPath, 110))}";
            if (c.Description is not null) value += $"<br>{Esc(Short(c.Description, 90))}";
            sb.AppendLine($"| {c.Rank} | {value} | {c.Kind}{(c.Status == "new" ? "" : $" ({c.Status})")} | {c.Score} | {Esc(BinaryText(c))} | {Esc(string.Join("; ", c.Reasons.Skip(1)))} |");
        }
        sb.AppendLine();
    }

    private static string BinaryText(Candidate c)
    {
        if (c.Binaries.Count == 0) return "—";
        var first = c.Binaries[0];
        var text = $"{first.Path} {first.Version}".Trim();
        if (c.BinaryCount > 1) text += $" (+{c.BinaryCount - 1})";
        if (c.OldBinaries is { Count: > 0 }) text += $"; previously: {Path.GetFileName(c.OldBinaries[0])}";
        return text;
    }

    private static void Row(StringBuilder sb, string label, string a, string b) => sb.AppendLine($"| {label} | {Esc(a)} | {Esc(b)} |");

    private static string Origin(FingerprintSide s) =>
        string.Create(Inv, $"{(s.Live ? "running" : "offline")} ({s.Root}), {(s.Elevated ? "elevated" : "not elevated")}, {s.CreatedUtc:yyyy-MM-dd}");

    private static void Omitted(StringBuilder sb, FingerprintPrivacyInfo? privacy, string key, string what)
    {
        var n = privacy?.Get(key) ?? 0;
        if (n > 0) sb.AppendLine($"- _{n.ToString("N0", Inv)} {what} omitted (privacy)._");
    }

    private static void More(StringBuilder sb, int total)
    {
        if (total > MaxRowsPerList) sb.AppendLine($"- … and {total - MaxRowsPerList} more (see the JSON).");
    }

    private static string KindTitle(string kind) => kind switch
    {
        InventoryKinds.Services => "Services",
        InventoryKinds.Drivers => "Drivers",
        InventoryKinds.Tasks => "Scheduled tasks",
        InventoryKinds.Appx => "Apps (appx)",
        InventoryKinds.Features => "Optional features",
        InventoryKinds.Capabilities => "Capabilities",
        InventoryKinds.Autoruns => "Autoruns",
        _ => kind,
    };

    private static string ChangeTitle(DiffChange c) => c switch
    {
        DiffChange.Added => "Added",
        DiffChange.Removed => "Removed",
        _ => "Changed",
    };

    private static string Sign(DiffChange c) => c switch { DiffChange.Added => "+", DiffChange.Removed => "−", _ => "~" };

    private static string Short(string s, int max) => s.Length <= max ? s : s[..(max - 1)] + "…";

    /// <summary>The report may be shared: no SIDs and no current user name (they appear in per-user task names).</summary>
    internal static string Redact(string s)
    {
        s = System.Text.RegularExpressions.Regex.Replace(s, @"S-1-5-21-[\d-]+", "S-1-5-21-…");
        var user = Environment.UserName;
        return user.Length >= 3 ? s.Replace(user, "<user>", StringComparison.OrdinalIgnoreCase) : s;
    }

    /// <summary>Text that is safe inside a table cell.</summary>
    internal static string Esc(string? s) =>
        Redact(s ?? "").Replace("\r", " ").Replace("\n", " ").Replace("|", "\\|").Replace("<", "&lt;").Replace(">", "&gt;");

    /// <summary>Inline code that is safe inside a table cell.</summary>
    internal static string Code(string? s) => $"`{Redact(s ?? "").Replace("`", "'").Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ")}`";
}
